function clone(value) {
  return structuredClone(value);
}

function fixed(value, digits = 2) {
  return Number(value).toFixed(digits);
}

function issueFrom(sourceText, mutate) {
  const source = JSON.parse(sourceText);
  mutate(source);
  assert.throws(
    () => portfolio.parseTransactions(JSON.stringify(source)),
    (error) =>
      error instanceof portfolio.PortfolioValidationError &&
      Array.isArray(error.issues) &&
      error.issues.length > 0,
  );
  try {
    portfolio.parseTransactions(JSON.stringify(source));
  } catch (error) {
    return error.issues;
  }
  throw new Error("invalid ledger unexpectedly parsed");
}

function assertIssue(sourceText, mutate, path, code) {
  const issues = issueFrom(sourceText, mutate);
  assert(
    issues.some((issue) => issue.path === path && issue.code === code),
    `expected ${path}:${code}, received ${JSON.stringify(issues)}`,
  );
}

function position(result, accountId, instrumentId) {
  return result.positionsByAccount.find(
    (entry) => entry.accountId === accountId && entry.instrumentId === instrumentId,
  );
}

