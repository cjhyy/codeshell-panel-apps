function makeWorkspaceHost({
  transactions = null,
  holdings = null,
  mutateAfterList = false,
  conflictOnWrite = false,
} = {}) {
  const files = new Map();
  if (transactions != null) {
    files.set("portfolio/transactions.json", {
      content: transactions,
      modifiedAt: 10,
      revision: "sha256:" + "1".repeat(64),
    });
  }
  if (holdings != null) {
    files.set("portfolio/holdings.json", {
      content: holdings,
      modifiedAt: 11,
      revision: "sha256:" + "2".repeat(64),
    });
  }
  const calls = [];
  let listed = false;
  const hostCall = async (method, params) => {
    calls.push({ method, params: clone(params) });
    if (method === "workspace.list") {
      const entries = [...files.entries()]
        .filter(([path]) => path.startsWith(`${params.path}/`))
        .map(([path, value]) => ({
          name: path.slice(params.path.length + 1),
          path,
          kind: "file",
          size: value.content.length,
          modifiedAt: value.modifiedAt,
        }));
      listed = true;
      return { path: params.path, entries, truncated: false };
    }
    if (method === "workspace.readText") {
      const file = files.get(params.path);
      if (!file) throw new Error("ENOENT: no such file or directory");
      return { path: params.path, ...file, size: file.content.length };
    }
    if (method === "workspace.writeText") {
      if (mutateAfterList && listed && params.path === "portfolio/transactions.json" && !files.has(params.path)) {
        files.set(params.path, {
          content: "external content",
          modifiedAt: 99,
          revision: "sha256:" + "9".repeat(64),
        });
      }
      if (conflictOnWrite && params.path === "portfolio/transactions.json") {
        const current = files.get(params.path);
        files.set(params.path, {
          content: current.content,
          modifiedAt: current.modifiedAt + 1,
          revision: "sha256:" + "8".repeat(64),
        });
      }
      const current = files.get(params.path);
      const conflicts =
        params.expectedModifiedAt === null
          ? current != null
          : current?.modifiedAt !== params.expectedModifiedAt ||
            (params.expectedRevision != null && current?.revision !== params.expectedRevision);
      if (conflicts) throw new Error("workspace file changed since it was opened");
      const next = {
        content: params.content,
        modifiedAt: (current?.modifiedAt ?? 100) + 1,
        revision: "sha256:" + "a".repeat(64),
      };
      files.set(params.path, next);
      return { path: params.path, modifiedAt: next.modifiedAt, revision: next.revision };
    }
    throw new Error(`unexpected host method ${method}`);
  };
  return { hostCall, files, calls };
}

