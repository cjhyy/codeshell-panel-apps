// Exact XIRR oracle. NPV(r) = sum a_j (1+r)^(-d_j/365). With g = gcd(d_j) and
// z = (1+r)^(-g/365) the NPV is an integer-exponent polynomial P(z) with exact
// rational (BigInt) coefficients. Sturm's theorem counts its distinct positive
// roots exactly; roots are isolated by Sturm-count bisection, so tangent and
// near-tangent pairs are resolved without any floating-point sign test.
function bigAbs(value) {
  return value < 0n ? -value : value;
}
function bigGcd(left, right) {
  let a = bigAbs(left);
  let b = bigAbs(right);
  while (b) [a, b] = [b, a % b];
  return a;
}
function rational(numerator, denominator = 1n) {
  if (denominator === 0n) throw new Error("zero denominator");
  let n = numerator;
  let d = denominator;
  if (d < 0n) {
    n = -n;
    d = -d;
  }
  const g = bigGcd(n, d) || 1n;
  return { n: n / g, d: d / g };
}
const qAdd = (a, b) => rational(a.n * b.d + b.n * a.d, a.d * b.d);
const qSub = (a, b) => rational(a.n * b.d - b.n * a.d, a.d * b.d);
const qMul = (a, b) => rational(a.n * b.n, a.d * b.d);
const qDiv = (a, b) => rational(a.n * b.d, a.d * b.n);
const qSign = (a) => (a.n < 0n ? -1 : a.n > 0n ? 1 : 0);
const qNumber = (a) => Number(a.n) / Number(a.d);
function qFromDecimalString(text) {
  const match = /^(-?)(\d+)(?:\.(\d+))?$/u.exec(text);
  if (!match) throw new Error(`oracle cannot parse ${text}`);
  const fraction = match[3] ?? "";
  const n = BigInt(`${match[1]}${match[2]}${fraction}`);
  return rational(n, 10n ** BigInt(fraction.length));
}
function qFromFloat(value) {
  const [mantissa, exponent] = value.toExponential(16).split("e");
  const base = qFromDecimalString(mantissa);
  const power = rational(10n ** BigInt(Math.abs(Number(exponent))));
  return Number(exponent) >= 0 ? qMul(base, power) : qDiv(base, power);
}
function polyTrim(poly) {
  while (poly.length && poly.at(-1).n === 0n) poly.pop();
  return poly;
}
function polyDerivative(poly) {
  return polyTrim(poly.slice(1).map((c, index) => qMul(c, rational(BigInt(index + 1)))));
}
function polyEvaluate(poly, x) {
  let acc = rational(0n);
  for (let index = poly.length - 1; index >= 0; index -= 1) acc = qAdd(qMul(acc, x), poly[index]);
  return acc;
}
function polyRemainder(dividend, divisor) {
  const remainder = dividend.slice();
  const degree = divisor.length - 1;
  const lead = divisor[degree];
  while (remainder.length && remainder.length - 1 >= degree) {
    const top = remainder.length - 1;
    const factor = qDiv(remainder[top], lead);
    for (let index = 0; index <= degree; index += 1) {
      remainder[top - degree + index] = qSub(remainder[top - degree + index], qMul(factor, divisor[index]));
    }
    polyTrim(remainder);
  }
  return remainder;
}
function sturmSequence(poly) {
  const sequence = [poly, polyDerivative(poly)];
  while (sequence.at(-1).length > 1) {
    const remainder = polyRemainder(sequence.at(-2), sequence.at(-1));
    if (!remainder.length) break;
    sequence.push(remainder.map((c) => rational(-c.n, c.d)));
  }
  return sequence.filter((entry) => entry.length);
}
function sturmVariations(sequence, x) {
  let previous = 0;
  let variations = 0;
  for (const poly of sequence) {
    const sign = qSign(polyEvaluate(poly, x));
    if (sign === 0) continue;
    if (previous !== 0 && sign !== previous) variations += 1;
    previous = sign;
  }
  return variations;
}
// Distinct real roots in the half-open interval (from, to].
const sturmCount = (sequence, from, to) => sturmVariations(sequence, from) - sturmVariations(sequence, to);
function xirrOracle(flows) {
  const byDate = new Map();
  for (const flow of flows) {
    byDate.set(flow.date, qAdd(byDate.get(flow.date) ?? rational(0n), qFromDecimalString(flow.amount)));
  }
  const entries = [...byDate].filter(([, amount]) => amount.n !== 0n).sort(([a], [b]) => a.localeCompare(b));
  if (entries.length < 2) return { inDomain: 0, positive: 0, roots: [] };
  const origin = Date.parse(`${entries[0][0]}T00:00:00Z`);
  const days = entries.map(([date]) => Math.round((Date.parse(`${date}T00:00:00Z`) - origin) / 86_400_000));
  let g = 0;
  for (const day of days) {
    let a = g;
    let b = day;
    while (b) [a, b] = [b, a % b];
    g = a;
  }
  const poly = Array.from({ length: days.at(-1) / g + 1 }, () => rational(0n));
  entries.forEach(([, amount], index) => {
    poly[days[index] / g] = amount;
  });
  polyTrim(poly);
  const sequence = sturmSequence(poly);
  // Supported r domain [-1 + 1e-12, 1e6] mapped to z (decreasing), widened by 1e-12.
  const zLow = qFromFloat((1e6 + 1) ** (-g / 365) * (1 - 1e-12));
  const zHigh = qFromFloat(1e12 ** (g / 365) * (1 + 1e-12));
  const lead = poly.at(-1);
  let cauchy = rational(1n);
  for (const c of poly) {
    const ratio = rational(bigAbs(c.n) * lead.d, c.d * bigAbs(lead.n));
    if (qSign(qSub(ratio, cauchy)) > 0) cauchy = ratio;
  }
  cauchy = qAdd(cauchy, rational(1n));
  if (qSign(qSub(cauchy, zHigh)) < 0) cauchy = qAdd(zHigh, rational(1n));
  const positive = sturmCount(sequence, rational(0n), cauchy);
  const inDomain = sturmCount(sequence, zLow, zHigh);
  const roots = [];
  const stack = [[zLow, zHigh, inDomain]];
  while (stack.length) {
    const [from, to, count] = stack.pop();
    if (count === 0) continue;
    if (count === 1) {
      let low = from;
      let high = to;
      for (let iteration = 0; iteration < 90; iteration += 1) {
        const middle = qDiv(qAdd(low, high), rational(2n));
        if (sturmCount(sequence, low, middle) === 1) high = middle;
        else low = middle;
      }
      roots.push(qNumber(high) ** (-365 / g) - 1);
      continue;
    }
    let middle = qDiv(qAdd(from, to), rational(2n));
    if (qSign(polyEvaluate(poly, middle)) === 0) middle = qDiv(qAdd(from, qMul(to, rational(2n))), rational(3n));
    const lower = sturmCount(sequence, from, middle);
    stack.push([from, middle, lower], [middle, to, count - lower]);
  }
  return { inDomain, positive, roots: roots.sort((a, b) => a - b) };
}

